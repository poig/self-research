"""Can qlto_qml load an ARBITRARY dataset, and what does that cost? The QRAM question.

qlto_qml claims three circuits per epoch, flat in |D| and in M, and supplement
v123/v124 back that at tier A. But the claim is about CIRCUIT COUNT, and this
file asks the question that decides whether the module is usable on a real
dataset: what dataset can it actually hold?

WHAT THE CURRENT ENCODER CAN REPRESENT. qlto_qml._encode applies CRY(alpha[j,d])
to system qubit j controlled on register qubit d, so the angle vector for sample
x is

    ang_j(x) = sum_d alpha[j,d] * bit_d(x)

a LINEAR function of the register bits. The |D| = 2^d samples are therefore not
free: they are the 2^d vertices of a parallelepiped generated by the columns of
alpha, embedded in angle space. A real dataset is not a parallelepiped. So the
register as built is a structured-data device, not a data loader, unless the
encoder is changed.

WHAT CHANGING IT COSTS. An arbitrary angle table A[j, x] is loadable - it is a
uniformly controlled RY over ALL d register qubits, one per system qubit, which
is exactly the mux_ry qlto_qml already carries for state preparation. The
question is the price, and the price is the whole answer:

    linear encoder      n_sys * d          rotations  =  n_sys * log2|D|
    arbitrary encoder   n_sys * 2^d        rotations  =  n_sys * |D|

so CIRCUIT COUNT stays at three while GATE COUNT goes from logarithmic in |D| to
linear in it. That is the QRAM wall in its usual form, and this file measures
where it actually sits rather than asserting the exponent.

THE THREE THINGS MEASURED

  1. EXPRESSIVITY. Fit the linear encoder's alpha to a random target angle table
     by least squares and report the residual. If the linear form could represent
     arbitrary data the residual would be ~0 and there would be no problem to
     solve.
  2. CORRECTNESS of the arbitrary encoder - does the mux-loaded register actually
     produce the requested f_x for every sample?
  3. COST - gates, two-qubit gates and depth for both encoders as |D| grows, and
     whether cos and the three-circuit count survive the swap.

TIER (project rule R1): mixed and labelled per part. Part 1 is a least-squares
fit with NO CIRCUIT - it is a structural fact about what a linear map can
represent, which R1 permits, and it supports no cost or accuracy figure. Part 2
is tier B (Statevector, exact amplitudes) because it asks an exactness question -
does the encoder encode - and claims nothing about shots. Part 3 is tier A:
transpiled circuits and, for the cos column, AerSimulator with finite shots
through qlto_qml.QLTOQML itself.
"""
import contextlib
import io
import os
import sys

import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from qiskit import QuantumCircuit, QuantumRegister, transpile
from qiskit.circuit.library import efficient_su2
from qiskit.quantum_info import Statevector
from qiskit_aer import AerSimulator

from qlto_qml import QLTOQML, mux_ry, _cry

N_SYS = 3
SHOTS = 32768
BASIS = ['rz', 'sx', 'x', 'cx']


def _cos(a, b):
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    return float(np.dot(a, b) / (na * nb)) if na > 1e-12 and nb > 1e-12 else 0.0


def bits_matrix(d):
    """B[x, k] = bit k of x. The design matrix the linear encoder is stuck with."""
    return np.array([[(x >> k) & 1 for k in range(d)] for x in range(1 << d)],
                    dtype=float)


class ArbitraryQML(QLTOQML):
    """qlto_qml with the linear encoder replaced by a per-sample angle table.

    angles[j, x] is the rotation applied to system qubit j for sample x, with no
    constraint relating different x. Everything else - the weighted register, the
    two sign branches, the V6 gradient - is inherited unchanged, which is the
    point: only the encoder differs.
    """

    def __init__(self, core, angles, y, **kw):
        angles = np.asarray(angles, float)
        n_sys, S = angles.shape
        d = int(np.log2(S))
        if 1 << d != S:
            raise ValueError("angle table has %d columns, not a power of two" % S)
        # the base class reads alpha.shape for (n_sys, n_data); hand it a dummy
        # of the right shape and override every use of its VALUES below
        super().__init__(core, np.zeros((n_sys, d)), y, **kw)
        self.angles = angles

    def _encode(self, qc, dq, sq):
        for j in range(self.n_sys):
            mux_ry(qc, self.angles[j], [dq[k] for k in range(self.n_data)], sq[j])

    def f_exact(self, x, theta):
        qc = QuantumCircuit(self.n_sys)
        for j in range(self.n_sys):
            qc.ry(float(self.angles[j, x]), j)
        qc.compose(self.core.assign_parameters(np.asarray(theta, float)),
                   inplace=True)
        return float(np.real(Statevector(qc).expectation_value(self.O_sys)))


