print("PART 1  what can the linear encoder represent?   NO CIRCUIT (tier C)")
print("-" * 100)
print("  ang_j(x) = sum_d alpha[j,d]*bit_d(x) is linear in the register bits, so")
print("  the reachable angle tables form a d-dimensional subspace of R^(2^d).")
print("  Least-squares fit of alpha to a random target table, per sample size:")
print()
print("      d   |D|   free params   rel. residual   variance captured")
print("   " + "-" * 68)
rng = np.random.default_rng(3)
for d in (2, 3, 4, 5):
    S = 1 << d
    B = bits_matrix(d)
    tgt = rng.uniform(-np.pi, np.pi, (N_SYS, S))
    alpha, *_ = np.linalg.lstsq(B, tgt.T, rcond=None)
    resid = tgt.T - B @ alpha
    rel = float(np.linalg.norm(resid) / np.linalg.norm(tgt))
    print("   %4d  %4d      %4d          %.4f          %5.1f%%"
          % (d, S, N_SYS * d, rel, 100 * (1 - rel ** 2)))
print()
print("  The linear encoder holds n_sys*d numbers and an arbitrary table needs")
print("  n_sys*2^d, so the residual grows with d and the register is a")
print("  STRUCTURED-DATA device as built. It cannot load a general dataset.")
print()

# ------------------------------------------------------------------ PART 2
print("-" * 100)
print("PART 2  does the mux encoder actually load an arbitrary table?   tier B")
print("-" * 100)
print("  Exact amplitudes. Compare f_x read out of the register circuit against")
print("  f_x from directly preparing sample x's angles. Exactness question, so")
print("  no shots and no cost figure here.")
print()
print("      d   |D|   max |f_reg - f_direct|   verdict")
print("   " + "-" * 60)
ok2 = True
for d in (2, 3, 4):
    S = 1 << d
    angles = rng.uniform(-np.pi, np.pi, (N_SYS, S))
    core = efficient_su2(N_SYS, reps=1)
    theta = rng.uniform(-np.pi, np.pi, core.num_parameters)
    q = ArbitraryQML(core, angles, np.zeros(S), shot_budget=SHOTS, sim_seed=1)

    # read every f_x out of ONE register circuit, exactly, by conditioning the
    # joint statevector on the register outcome
    dq = QuantumRegister(d, 'd'); sq = QuantumRegister(N_SYS, 's')
    qc = QuantumCircuit(dq, sq)
    from qlto_qml import prep_weights
    prep_weights(qc, np.ones(S) / S, dq)
    q._encode(qc, dq, sq)
    qc.compose(core.assign_parameters(theta), qubits=list(sq), inplace=True)
    psi = Statevector(qc).data.reshape([2] * (N_SYS + d))

    worst = 0.0
    for x in range(S):
        idx = [slice(None)] * (N_SYS + d)
        for k in range(d):                      # register qubit k is axis -(k+1)
            idx[-(k + 1)] = (x >> k) & 1
        blk = np.asarray(psi[tuple(idx)]).ravel()
        nrm = np.vdot(blk, blk).real
        # system qubit 0 is the LAST axis of the remaining block
        sub = blk.reshape([2] * N_SYS)
        p0 = float(np.sum(np.abs(sub[..., 0]) ** 2))
        p1 = float(np.sum(np.abs(sub[..., 1]) ** 2))
        f_reg = (p0 - p1) / max(nrm, 1e-300)
        worst = max(worst, abs(f_reg - q.f_exact(x, theta)))
    ok2 &= worst < 1e-9
    print("   %4d  %4d          %.2e            %s"
          % (d, S, worst, "ok" if worst < 1e-9 else "FAIL"))
print()
if not ok2:
    print("   FAIL - the arbitrary encoder does not encode; PART 3 would be noise.")
    sys.exit(1)
print("   PASS - an arbitrary dataset IS loadable. The rest is what it costs.")
