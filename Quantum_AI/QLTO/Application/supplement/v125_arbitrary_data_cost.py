be = AerSimulator(seed_simulator=5)
cost = {}
for d in (2, 3, 4, 5):
    S = 1 << d
    core = efficient_su2(N_SYS, reps=1)
    theta = rng.uniform(-np.pi, np.pi, core.num_parameters)
    y = rng.integers(0, 2, S) * 2.0 - 1.0
    tgt = rng.uniform(-np.pi, np.pi, (N_SYS, S))
    B = bits_matrix(d)
    alpha_fit, *_ = np.linalg.lstsq(B, tgt.T, rcond=None)

    for tag in ('linear', 'arbitrary'):
        if tag == 'linear':
            q = QLTOQML(core, alpha_fit.T, y, shot_budget=SHOTS, sim_seed=5,
                        backend=be)
        else:
            q = ArbitraryQML(core, tgt, y, shot_budget=SHOTS, sim_seed=5,
                             backend=be)
        qc = q.batched(np.ones(S) / S)
        t = transpile(qc.assign_parameters(theta), basis_gates=BASIS,
                      optimization_level=1)
        ops = t.count_ops()
        g2 = ops.get('cx', 0)
        c0 = q.ncircuits
        with contextlib.redirect_stdout(io.StringIO()):
            f, _den = q.f_hat(theta)
            g_est, _ = q.gradient(theta, w=f - y)
        g_true, _ = q.grad_exact(theta)
        cost[(d, tag)] = (sum(ops.values()), g2, t.depth())
        print("   %4d  %4d   %-10s  %5d      %5d    %5d      %2d      %+.4f"
              % (d, S, tag, sum(ops.values()), g2, t.depth(),
                 q.ncircuits - c0, _cos(g_est, g_true)))
    print()

