"""
plot_hardware_results.py

Visualizes the bifurcation diagram from the IBM Quantum hardware scan.
Reads the JSON data generated by ibm_runner.py.
"""

import json
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path
import glob

DATA_DIR = Path('../data/hardware')
FIGURES_DIR = Path('../figures')
FIGURES_DIR.mkdir(parents=True, exist_ok=True)

def load_latest_data():
    # Find the most recent json file
    # We want to consider ALL scan files and pick the absolute latest
    files = []
    files.extend(glob.glob(str(DATA_DIR / 'scan_stacked_*.json')))
    files.extend(glob.glob(str(DATA_DIR / 'scan_qbraid_*.json')))
    files.extend(glob.glob(str(DATA_DIR / 'scan_batch_*.json')))
    
    if not files:
        raise FileNotFoundError("No data files found in ../data/hardware")
        
    latest_file = max(files, key=lambda f: Path(f).stat().st_mtime)
    print(f"Loading data from: {latest_file}")
    
    with open(latest_file, 'r') as f:
        data = json.load(f)
    return data

def plot_bifurcation(data):
    plt.figure(figsize=(10, 6))
    
    # Data is {str(r): [x0, x1, ...]}
    r_values = sorted([float(k) for k in data.keys()])
    
    # Plot Hardware Data
    for r_val, energies in data.items():
        r = float(r_val)
        # Plot last 20 points (steady state)
        steady_state = energies[-20:]
        plt.scatter([r] * len(steady_state), steady_state, color='black', s=1, alpha=0.6)

    # Overlay Theoretical Bifurcation
    print("Overlaying theoretical curves...")
    r_theory = np.linspace(0.6, 0.8, 500)
    x_theory = []
    for r in r_theory:
        # Iterate map
        x = 0.5
        # Transient
        for _ in range(200):
            x = r * np.sin(np.pi * x)**2
        # Steady state
        for _ in range(50):
            x = r * np.sin(np.pi * x)**2
            x_theory.append((r, x))
    
    x_theory = np.array(x_theory)
    plt.plot(x_theory[:, 0], x_theory[:, 1], 'r.', markersize=0.1, alpha=0.3, label='Theory (sin² map)')

    plt.title('VQA Bifurcation: Hardware (Black) vs Theory (Red)', fontsize=14)
    plt.xlabel('Control Parameter r', fontsize=12)
    plt.ylabel('Normalized Energy', fontsize=12)
    plt.grid(True, alpha=0.3)
    plt.legend()
    
    output_path = FIGURES_DIR / 'hardware_bifurcation_overlay.png'
    plt.savefig(output_path, dpi=300)
    print(f"Saved overlay plot to {output_path}")

if __name__ == "__main__":
    try:
        data = load_latest_data()
        plot_bifurcation(data)
    except Exception as e:
        print(f"Error: {e}")
